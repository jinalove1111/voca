// 구동해 요청/응답을 관측한다. production에는 요청을 보내지 않는다.
//
// 검증 시나리오(운영자 지정):
//   · concurrent duplicate — 같은 이벤트 동시 다발 요청
//   · replay             — 같은 요청 반복 재생
//   · malformed request  — 형식/타입/소스 위조
//   · 다른 학생 ID 변조   — 남의 studentId로 지급 시도
//   · daily cap          — 상한 도달 후 거부
//   · fail-closed        — 검증 쿼리 실패 시 지급 안 함
//
// 하네스: api/grant-xp.js를 esbuild로 번들하되 @supabase/supabase-js만
// 인메모리 가짜 구현으로 치환한다. 핸들러 코드 자체는 한 글자도 바꾸지 않고
// 그대로 실행된다 — "테스트를 위해 production 코드를 고치지 않는다"는 원칙.
// 산출물은 scripts/.tmp/(gitignore).
//
// 등록: npm run verify:reward-hardening-behavior
// 네트워크 0, production 요청 0, DB 무접촉.


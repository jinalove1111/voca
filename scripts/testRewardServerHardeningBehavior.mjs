const fake = await import(fakeUrl)
const handler = (await import(pathToFileURL(outfile).href)).default
const { REWARD_DAILY_CAP } = await import('../src/utils/rewardEngine.js')

let failures = 0, asserted = 0
function check(label, cond) {
  asserted++
  if (cond) console.log(`  PASS  ${label}`)
  else { console.log(`  FAIL  ${label}`); failures++ }
}

const STUDENT = '11111111-2222-4333-8444-555555555555'
const OTHER = '99999999-8888-4777-8666-555555555555'
const TEST_ID = 'aaaaaaaa-bbbb-4ccc-8ddd-eeeeeeeeeeee'
const today = new Date().toDateString()

function res() {
  const r = { code: null, body: null }
  r.status = (c) => { r.code = c; return r }
  r.json = (b) => { r.body = b; return r }
  return r
}
const post = (body) => { const r = res(); return handler({ method: 'POST', body }, r).then(() => r) }
function seed({ student = true, examResult = false } = {}) {
  fake.__reset()
  if (student) fake.__db.students.push({ id: STUDENT })
  if (examResult) fake.__db.entrance_test_results.push({ test_id: TEST_ID, student_id: STUDENT })
}
const ledger = () => fake.__db.reward_ledger

console.log('\n1. 정상 지급 (기준선 — 강화가 정상 동작을 막지 않는가)')
{
  seed()
  const r = await post({ ledger: 'reward', studentId: STUDENT, rewardType: 'word-session-complete', sourceType: 'daily-words', sourceId: today })
  check(`정상 요청 성공 (응답 ${JSON.stringify(r.body)})`, r.body?.ok === true && r.body?.duplicate === false)
  check('원장 1건 기록', ledger().length === 1)
  check('금액은 서버 결정(1별)', ledger()[0]?.stars_delta === 1)
}

console.log('\n2. replay — 같은 요청 10회 반복')
{
  seed()
  const body = { ledger: 'reward', studentId: STUDENT, rewardType: 'daily-goal-complete', sourceType: 'daily-goal', sourceId: today }
  const rs = []
  for (let i = 0; i < 10; i++) rs.push(await post(body))
  check('원장 1건만 (10회 재생)', ledger().length === 1)
  check('2회차부터 duplicate:true 응답', rs.slice(1).every(r => r.body?.duplicate === true))
  check('첫 회만 duplicate:false', rs[0].body?.duplicate === false)
}

console.log('\n3. concurrent duplicate — Promise.all 동시 20회')
{
  seed()
  const body = { ledger: 'reward', studentId: STUDENT, rewardType: 'writing-complete', sourceType: 'daily-writing', sourceId: today }
  await Promise.all(Array.from({ length: 20 }, () => post(body)))
  check('동시 20회 -> 원장 1건', ledger().length === 1)
  check('지급액 2별 1회분', ledger().reduce((a, r) => a + r.stars_delta, 0) === 2)
}

console.log('\n4. malformed request — 형식/타입/소스 위조')
{
  seed()
  const cases = [
    ['rewardType 위조', { rewardType: 'free-stars', sourceType: 'daily-words', sourceId: today }, 'unknown_reward_type'],
    ['legacy-baseline 지급 시도', { rewardType: 'legacy-baseline', sourceType: 'migration', sourceId: 'v1' }, 'unknown_reward_type'],
    ['sourceType 불일치', { rewardType: 'word-session-complete', sourceType: 'daily-goal', sourceId: today }, 'invalid_reward_source'],
    ['날짜 자리에 임의 문자열', { rewardType: 'word-session-complete', sourceType: 'daily-words', sourceId: 'not-a-date' }, 'invalid_reward_source'],
    ['studentId 형식 위조', { studentId: 'not-a-uuid', rewardType: 'word-session-complete', sourceType: 'daily-words', sourceId: today }, 'invalid_student_id'],
    ['streak 범위 초과', { rewardType: 'streak-bonus', sourceType: 'streak', sourceId: `${today}:9999` }, 'invalid_reward_source'],
  ]
  for (const [label, patch, expect] of cases) {
    const r = await post({ ledger: 'reward', studentId: STUDENT, ...patch })
    check(`${label} -> ${expect}`, r.body?.ok === false && r.body?.reason === expect)
  }
  check('malformed 요청들이 원장에 아무것도 남기지 않음', ledger().length === 0)
}

console.log('\n5. ★ 다른 학생 ID 변조 — 존재하지 않는 학생')
{
  seed() // STUDENT만 등록, OTHER는 students에 없음
  const r = await post({ ledger: 'reward', studentId: OTHER, rewardType: 'word-session-complete', sourceType: 'daily-words', sourceId: today })
  check('미존재 학생 -> student_not_found 거부', r.body?.ok === false && r.body?.reason === 'student_not_found')
  check('원장에 기록 없음', ledger().length === 0)
}

console.log('\n6. ★ exam-complete — 임의 UUID 위조 차단 (HIGH 2)')
{
  seed({ examResult: false }) // 제출 기록 없음
  const forged = await post({ ledger: 'reward', studentId: STUDENT, rewardType: 'exam-complete', sourceType: 'entrance-test', sourceId: TEST_ID })
  check('제출 기록 없는 시험 -> exam_result_not_found 거부', forged.body?.reason === 'exam_result_not_found')
  check('원장 기록 0', ledger().length === 0)

  seed({ examResult: true }) // 실제 제출 있음
  const ok = await post({ ledger: 'reward', studentId: STUDENT, rewardType: 'exam-complete', sourceType: 'entrance-test', sourceId: TEST_ID })
  check('실제 제출한 시험은 정상 지급 (무회귀)', ok.body?.ok === true)
  check('지급액 2별', ledger()[0]?.stars_delta === 2)

  // 임의 UUID 100개를 만들어 파밍 시도
  seed({ examResult: true })
  let granted = 0
  for (let i = 0; i < 100; i++) {
    const rnd = `${String(i).padStart(8, '0')}-bbbb-4ccc-8ddd-eeeeeeeeeeee`
    const rr = await post({ ledger: 'reward', studentId: STUDENT, rewardType: 'exam-complete', sourceType: 'entrance-test', sourceId: rnd })
    if (rr.body?.ok === true) granted++
  }
  check(`임의 UUID 100개 파밍 시도 -> 지급 ${granted}건 (0이어야 함)`, granted === 0)
}

console.log('\n7. ★ daily cap — wrong-word-recovered 무제한 차단 (HIGH 3·4)')
{
  seed()
  const cap = REWARD_DAILY_CAP['wrong-word-recovered']
  let ok = 0, capped = 0
  for (let i = 0; i < cap + 25; i++) {
    const r = await post({ ledger: 'reward', studentId: STUDENT, rewardType: 'wrong-word-recovered', sourceType: 'spelling-review', sourceId: `${today}:w${i}` })
    if (r.body?.ok === true) ok++
    else if (r.body?.reason === 'daily_cap_reached') capped++
  }
  check(`상한 ${cap}건까지만 지급 (실제 ${ok})`, ok === cap)
  check(`초과분은 daily_cap_reached로 거부 (${capped}건)`, capped === 25)
  check(`원장 ${cap}건 (무제한 아님)`, ledger().length === cap)
  check(`하루 최대 부풀림 ${cap}별로 유한`, ledger().reduce((a, r) => a + r.stars_delta, 0) === cap)
}

console.log('\n8. fail-closed — 검증 쿼리가 실패하면 지급하지 않는다')
{
  seed()
  fake.__fail.students = { code: 'XX000', message: 'boom' }
  const r1 = await post({ ledger: 'reward', studentId: STUDENT, rewardType: 'word-session-complete', sourceType: 'daily-words', sourceId: today })
  check('학생 조회 실패 -> student_lookup_failed, 지급 안 함', r1.body?.reason === 'student_lookup_failed' && ledger().length === 0)

  seed({ examResult: true })
  fake.__fail.entrance_test_results = { code: 'XX000', message: 'boom' }
  const r2 = await post({ ledger: 'reward', studentId: STUDENT, rewardType: 'exam-complete', sourceType: 'entrance-test', sourceId: TEST_ID })
  check('시험 조회 실패 -> exam_lookup_failed, 지급 안 함', r2.body?.reason === 'exam_lookup_failed' && ledger().length === 0)

  seed()
  fake.__failOp.maybeSingle = { code: 'XX000', message: 'boom' }
  const r3 = await post({ ledger: 'reward', studentId: STUDENT, rewardType: 'word-session-complete', sourceType: 'daily-words', sourceId: today })
  check('재시도 선판정 실패 -> dup_check_failed, 지급 안 함', r3.body?.reason === 'dup_check_failed' && ledger().length === 0)

  seed()
  fake.__failOp.count = { code: 'XX000', message: 'boom' }
  const r4 = await post({ ledger: 'reward', studentId: STUDENT, rewardType: 'word-session-complete', sourceType: 'daily-words', sourceId: today })
  check('상한 집계 실패 -> cap_check_failed, 지급 안 함', r4.body?.reason === 'cap_check_failed' && ledger().length === 0)
}

console.log('\n9. 테이블 미존재(42P01) 폴백은 유지 — 상한 검사가 이를 깨지 않는가')
{
  seed()
  fake.__fail.reward_ledger = { code: '42P01', message: 'relation does not exist' }
  const r = await post({ ledger: 'reward', studentId: STUDENT, rewardType: 'word-session-complete', sourceType: 'daily-words', sourceId: today })
  check('table_missing으로 무해 폴백(cap_check_failed 아님)', r.body?.reason === 'table_missing')
}

console.log('\n10. 기존 XP 경로 무회귀 — reward 분기가 XP를 건드리지 않는가')
{
  seed()
  const r = await post({ studentId: STUDENT, eventType: 'word-view-complete', sourceEventId: `word-view-complete:${new Date().toISOString().slice(0, 10)}` })
  check('ledger 필드 없는 요청은 XP 분기로 흘러간다(reward 응답 아님)',
    r.body?.reason !== 'student_not_found' && r.body?.reason !== 'daily_cap_reached')
  check('reward_ledger에 기록되지 않음', fake.__db.reward_ledger.length === 0)
}

console.log(`\n총 단언 ${asserted}개 중 실패 ${failures}개`)
console.log(failures === 0 ? '모든 단언 통과 — 서버 강화 동작 검증 ✅' : `${failures}개 단언 실패 ❌`)
process.exit(failures === 0 ? 0 : 1)

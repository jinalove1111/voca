// Reward System V1 — 동시성/부하 매트릭스 (2026-08-22 야간 감사, Phase 4).
//
// 기존 자산과의 관계(대체하지 않음, 위에 얹음):
//   - scripts/testRewardFlow.mjs           : "각 앵커가 정상 배선됐는가"(1~2회 호출)
//   - scripts/testRewardIdempotencyStress.mjs : "심한 중복 호출에도 1회만"(<=10회, 순차)
//   - 이 파일                                : "2/5/10/50/100회를 **한 tick 안에서**
//                                              몰아쳐도" 불변식이 지켜지는가 +
//                                              Promise.all 동시 요청 + 6개 앵커 전수
//
// 검증하는 단일 불변식(운영자 정의):
//   ONE ELIGIBLE ACTION = ONE REWARD EVENT = ONE LEDGER ENTRY = ONE BALANCE CHANGE
//   여기에 서버 축을 하나 더 붙여 검증한다: POST(postRewardEvent) <= 1회.
//
// 구동 방식은 scripts/testRewardIdempotencyStress.mjs와 동일한 하네스를
// 그대로 재사용한다(fakeReact.mjs + 자체 esbuild 번들 + wordLibrary 스텁).
// 새 프레임워크를 발명하지 않는다. 번들/스텁 산출물 경로만 이 파일 전용으로
// 분리해(scripts/.tmp/useStudent.concurrency.bundle.mjs,
// scripts/.tmp/wordLibraryConcurrencyStub.mjs) 기존 테스트의 산출물과
// 충돌하지 않게 한다 — 기존 파일은 한 글자도 건드리지 않는다(규칙 16).
//
// production 소스 무접촉. 네트워크 0. Supabase 0. 학생 데이터 0.
//
// 등록: npm run verify:reward-concurrency

let expectedUnhandledRejections = 0
process.on('unhandledRejection', () => { expectedUnhandledRejections++ })


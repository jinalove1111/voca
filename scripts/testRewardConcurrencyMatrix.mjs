import { createFakeClock, renderHook } from './fakeReact.mjs'
import { earnedStars, REWARD_STARS, rewardIdempotencyKey } from '../src/utils/rewardEngine.js'

// ── 1) 번들 준비 ────────────────────────────────────────────────────────
const TMP_DIR = path.resolve('scripts/.tmp')
fs.mkdirSync(TMP_DIR, { recursive: true })

const raceStubUrl = pathToFileURL(path.resolve('scripts/wordLibraryRaceStub.mjs')).href
const reactStubPath = path.resolve('scripts/fakeReactModule.mjs')

const generatedStubPath = path.join(TMP_DIR, 'wordLibraryConcurrencyStub.mjs')
fs.writeFileSync(generatedStubPath, `// AUTO-GENERATED by scripts/testRewardConcurrencyMatrix.mjs — do not edit by hand.
export * from ${JSON.stringify(raceStubUrl)}
export const __postRewardEventLog = []
let __delayMs = 0
export function __setPostRewardEventDelay(ms) { __delayMs = ms }
export function __resetPostRewardEventProbe() { __postRewardEventLog.length = 0; __delayMs = 0 }
export async function postRewardEvent(studentId, rewardType, sourceType, sourceId) {
  __postRewardEventLog.push({ studentId, rewardType, sourceType, sourceId })
  if (__delayMs > 0) await new Promise((r) => setTimeout(r, __delayMs))
}
`, 'utf8')
const generatedStubUrl = pathToFileURL(generatedStubPath).href


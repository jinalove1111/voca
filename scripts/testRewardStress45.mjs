// ── 6) 메인 매트릭스 — 동시성 레벨별로 DB를 완전히 리셋하고, 각 레벨에서
//    12타입 x 9시나리오를 그 레벨의 학생 수만큼 배치 실행한다. 표는
//    레벨을 합산해 12x9=108행으로 출력(레벨별 108x4=432행은 가독성을
//    해쳐 생략 — 레벨별 통과/실패는 아래 3개 집계 단언으로 별도 확인).
const CONCURRENCY_LEVELS = [5, 10, 20, 45]
const summary = new Map() // `${type}::${scenarioKey}` -> {rows,duplicates,mismatches,attempts}

for (const N of CONCURRENCY_LEVELS) {
  fakeDb.__reset()
  const batch = STUDENTS.slice(0, N)
  for (const sid of batch) fakeDb.__db.students.push({ id: sid })

  for (const type of REWARD_TYPES) {
    for (const scenario of SCENARIOS) {
      const runOne = async (studentId, idx) => {
        // 선형(seedBase + idx*k) 조합은 streak-bonus([3,5,7], mod3)/spelling-combo
        // ([3,5,10], mod3) 같은 짧은 순환주기 값 선택과 우연히 주기적으로 aliasing되어
        // (예: 3칸 간격 시나리오가 서로 같은 streak 값을 골라 "같은 sourceId"가 되는
        // 우연의 일치) 요약표의 rows가 실제로 그 시나리오가 새로 만든 행이 아니라
        // 이전 시나리오가 이미 만든 행을 가리키는 착시를 만든다(무결성 단언 자체는
        // 영향 없음 — auditKey는 항상 실제 key 기준으로 정확 — 표의 가독성 문제만).
        // 문자열 해시로 끊어 각 (타입,시나리오,학생인덱스) 조합이 독립적인 값을
        // 고르게 한다.
        const hash = (s) => { let h = 0; for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0; return h }
        const a = hash(`${type}|${scenario.key}|${idx}|a`)
        const b = hash(`${type}|${scenario.key}|${idx}|b`)
        try { return await scenario.run(type, studentId, a, b) }
        catch (e) { return { __error: String(e && e.message || e) } }
      }
      const results = scenario.sequential
        ? await (async () => { const out = []; for (let i = 0; i < batch.length; i++) out.push(await runOne(batch[i], i)); return out })()
        : await Promise.all(batch.map((sid, i) => runOne(sid, i)))

      const bucketKey = `${type}::${scenario.key}`
      const bucket = summary.get(bucketKey) || { rows: 0, duplicates: 0, mismatches: 0, attempts: 0, errors: 0 }
      for (const r of results) {
        bucket.attempts++
        if (r && r.__error) { bucket.errors++; continue }
        for (const item of r) {
          const a = auditKey(item.key, item.studentId, item.type, item.variant)
          bucket.rows += a.rows
          bucket.duplicates += a.duplicate
          bucket.mismatches += a.mismatch
        }
      }
      summary.set(bucketKey, bucket)
    }
  }

  const levelDuplicates = [...summary.values()].reduce((s, b) => s + b.duplicates, 0)
  const levelMismatches = [...summary.values()].reduce((s, b) => s + b.mismatches, 0)
  const levelErrors = [...summary.values()].reduce((s, b) => s + b.errors, 0)
  console.log(`\n동시성 레벨 N=${N} 완료 — 누적 중복 ${levelDuplicates}, 누적 불일치 ${levelMismatches}, 시나리오 실행 예외 ${levelErrors}, 누적 HTTP500 ${http500Count}`)
  check(`N=${N}: 이 시점까지 누적 duplicate 0`, levelDuplicates === 0)
  check(`N=${N}: 이 시점까지 누적 mismatch 0`, levelMismatches === 0)
  check(`N=${N}: 이 시점까지 시나리오 실행 자체의 예외 0`, levelErrors === 0)
}


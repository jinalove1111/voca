async function scenarioUtcMidnight(type, studentId, seedA, seedB) {
  const idA = sourceIdFor(type, seedA)
  const idB = sourceIdFor(type, seedB)
  await seedIfNeeded(type, studentId, idA)
  if (idB !== idA) await seedIfNeeded(type, studentId, idB)
  const token = signSessionToken(studentId)
  const kstMidnightToday = kstDayStartMs(Date.now())
  const utcMidnightWithinKstDay = kstMidnightToday + 9 * 60 * 60 * 1000 // 같은 KST 날짜 안의 UTC 자정
  const tBefore = utcMidnightWithinKstDay - 500
  const tAfter = utcMidnightWithinKstDay + 500
  if (kstDayStartMs(tBefore) !== kstDayStartMs(tAfter)) throw new Error('픽스처 오류: tBefore/tAfter가 같은 KST 날짜가 아님')
  await withMockedNow(tBefore, () => call(bodyFor(type, studentId, idA), token))
  await withMockedNow(tAfter, () => call(bodyFor(type, studentId, idB), token))
  const keys = new Map()
  keys.set(keyFor(type, studentId, idA), rewardVariantFromSource(type, idA))
  keys.set(keyFor(type, studentId, idB), rewardVariantFromSource(type, idB))
  return [...keys.entries()].map(([key, variant]) => ({ key, studentId, type, variant }))
}


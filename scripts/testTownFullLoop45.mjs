  check(`N=${N}: 구매 후 owned에 tree 포함·cat 미포함 전원`,
    results.every((r) => r.shopAfter.body.owned.includes('tree') && !r.shopAfter.body.owned.includes('cat')))
  check(`N=${N}: 구매(cat locked 시도) 후에도 별 총량 불변(구매 실패가 별을 건드리지 않음)`,
    results.every((r) => r.shopAfter.body.starsEarned === r.shopBefore.body.starsEarned))
  check(`N=${N}: 구매 후에도 레벨 1 유지 전원(별 20 미만)`, results.every((r) => r.shopAfter.body.level === 1))

  // ── 원장 집계(전역) ───────────────────────────────────────────────────
  const expectedLedgerRows = students.reduce((s, _sid, i) => s + (isWrongWord(i) ? 5 : 3), 0)
  const ledgerRowsTotal = fakeDb.__db.reward_ledger.filter((e) => students.includes(e.student_id)).length
  check(`N=${N}: reward_ledger 총 행수 == ${expectedLedgerRows}(3 또는 5 x N)`, ledgerRowsTotal === expectedLedgerRows)

  const expectedDollarRows = expectedLedgerRows + N /* welcome */ + N /* tree 구매 */
  const dollarRowsTotal = fakeDb.__db.dollar_ledger.filter((e) => students.includes(e.student_id)).length
  check(`N=${N}: dollar_ledger 총 행수 == ${expectedDollarRows}(=보상 트리거행+welcome N+구매 N)`, dollarRowsTotal === expectedDollarRows)

  const welcomeGrantedCount = results.filter((r) => r.w1.body.granted || r.w2.body.granted).length
  check(`N=${N}: welcome 지급 학생 수 == N(=${N})`, welcomeGrantedCount === N)

  const treePurchases = fakeDb.__db.town_purchases.filter((p) => students.includes(p.student_id) && p.item_id === 'tree')
  check(`N=${N}: town_purchases(tree) == N(=${N}), 중복 0`,
    treePurchases.length === N && new Set(treePurchases.map((p) => p.student_id)).size === N)
  const catPurchases = fakeDb.__db.town_purchases.filter((p) => p.item_id === 'cat')
  check(`N=${N}: town_purchases(cat) == 0(전원 레벨1 미달로 잠김)`, catPurchases.length === 0)

  const lockedCount = results.filter((r) => r.buyCat.body.reason === 'locked').length

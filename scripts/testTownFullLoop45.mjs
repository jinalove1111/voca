  // ── 인증 실패 — 등록되지 않은(유령) 학생 토큰: 서명은 유효하나 students에
  //    없음 -> RPC 데이터 계층에서 실패, 부작용(행 생성) 0 ─────────────────
  const ghostId = crypto.randomUUID()
  const ghostToken = signSessionToken(ghostId)
  const ghostPurchase = await callTown('purchase_town_item', { itemId: 'tree' }, ghostToken)
  check(`N=${N}: 미등록(유령) 학생 토큰으로 구매 시도 -> student_not_found`,
    ghostPurchase.body.ok === false && ghostPurchase.body.reason === 'student_not_found')
  const ghostRows = fakeDb.__db.dollar_ledger.filter((e) => e.student_id === ghostId).length
    + fakeDb.__db.town_purchases.filter((p) => p.student_id === ghostId).length
  check(`N=${N}: 유령 학생 관련 행 0개(auth 실패가 어떤 부작용도 남기지 않음)`, ghostRows === 0)
  const invalidCount = itemNotFoundCount + 1 // 무효 아이템 N건 + 유령 학생 1건

  // ── 교차 오염(leak) — 명단 밖 학생 행 0, 호출자 본인 studentId만 등장 ──
  const foreignReward = fakeDb.__db.reward_ledger.filter((e) => !students.includes(e.student_id) && e.student_id !== ghostId)
  const foreignDollar = fakeDb.__db.dollar_ledger.filter((e) => !students.includes(e.student_id) && e.student_id !== ghostId)
  const foreignPurchase = fakeDb.__db.town_purchases.filter((p) => !students.includes(p.student_id))
  check(`N=${N}: 명단 밖 학생 행 0(reward/dollar/purchase 전부)`,
    foreignReward.length === 0 && foreignDollar.length === 0 && foreignPurchase.length === 0)

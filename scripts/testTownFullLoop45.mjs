function injectDollarFromReward(row) {
  const rate = DOLLAR_RATE_BY_REWARD_TYPE[row.reward_type]
  if (!(row.stars_delta > 0) || !rate) return
  const key = row.idempotency_key + ':dollar'
  if (__db.dollar_ledger.some((e) => e.idempotency_key === key)) return
  __db.dollar_ledger.push({
    student_id: row.student_id,
    event_type: 'reward:' + row.reward_type,
    dollars_delta: row.stars_delta * rate,
    source_type: row.source_type,
    source_id: row.source_id,
    idempotency_key: key,
  })
}


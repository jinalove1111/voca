    if (!placeRes.ok) placeFail++
    const pid = (host.result.townPlacements.find((p) => p.itemId === 'tree') || {}).placementId
    placementIdBySid.set(sid, pid)
    const moveRes = host.result.moveTownItem(pid, 1, 1)

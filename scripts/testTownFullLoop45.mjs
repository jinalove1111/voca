  // ==========================================================================
  // N=${N} — 배치 루프(useStudent 훅) — place → move → refresh → relogin
  // ==========================================================================
  section(`N=${N} — 배치 루프(useStudent 훅) — place → move → refresh → relogin`)
  const placementIdBySid = new Map()
  let placeFail = 0

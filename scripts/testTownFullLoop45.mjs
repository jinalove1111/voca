function tick() { return new Promise((r) => setImmediate(r)) }

function matchRow(row, filters) {
  return filters.every(([c, v]) => {
    if (c.startsWith('__gte__')) return String(row[c.slice(7)]) >= String(v)
    return String(row[c]) === String(v)
  })
}
function makeQuery(table) {
  const filters = []
  let headCount = false
  const q = {
    select(_cols, opts) { if (opts && opts.head) headCount = true; return q },
    eq(col, val) { filters.push([col, val]); return q },
    gte(col, val) { filters.push(['__gte__' + col, val]); return q },
    async maybeSingle() {
      await tick()
      const rows = __db[table] || []
      const hit = rows.find((r) => matchRow(r, filters))
      return { data: hit || null, error: null }
    },
    then(resolve, reject) {
      ;(async () => {
        await tick()
        const rows = __db[table] || []
        const hit = rows.filter((r) => matchRow(r, filters))
        resolve({ data: headCount ? null : hit, count: hit.length, error: null })
      })().catch(reject)
    },
  }
  return q
}


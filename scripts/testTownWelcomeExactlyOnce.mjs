// scripts/testTownWelcomeExactlyOnce.mjs
//
// Paul Town V1(2026-09-11) 환영 보상(claim_town_welcome, +20 Paul Dollar)이
// "학생 평생 정확히 1회"라는 계약을 10가지 동시성/재시도 시나리오에서
// 증명한다. api/grant-xp.js의 claim_town_welcome 분기(핸들러 코드는 한
// 글자도 바꾸지 않고 esbuild로 그대로 번들)를 scripts/testTownV1Server.mjs와
// 같은 패턴(가짜 @supabase/supabase-js + ./_pinAuth.js)으로 실행하되, 이
// 파일은 그 파일을 import하지 않고(둘 다 scripts/.tmp에 서로 다른 이름의
// 산출물을 쓴다) 독립적으로 하네스를 새로 구성한다.
//
// 가짜 RPC(grant_town_welcome_credit)는 supabase_v3_50_town_v1.sql의 실제
// 계약을 그대로 흉내낸다 —
//   idempotency_key = `${student_id}:welcome:town-v1`
//   insert ... on conflict (idempotency_key) do nothing
//   granted = (row_count > 0), balance_after = SUM(dollar_ledger.dollars_delta)
// 이 함수는 (구매 함수 purchase_town_item과 달리) advisory lock을 전혀 쓰지
// 않는다 — "정확히 1회"는 오직 dollar_ledger.idempotency_key의 UNIQUE
// 제약과 insert의 원자성만으로 보장된다(SQL 파일 본문 참고). 그래서 이
// 가짜 구현도 학생별 promise 락을 두지 않고, "중복 확인 + insert"를 두
// await 사이에 걸치지 않는 단일 동기 블록으로 작성해 JS 단일 스레드
// 특성이 Postgres UNIQUE 제약의 원자성과 동일한 보장을 제공하게 한다 —
// 두 "동시" 호출이 각자의 인위적 지연(tick/setTimeout)에서 깨어난 순서대로
// 정확히 하나만 그 블록을 통과한다.
//
// 지연(latency) 주입은 전역 FIFO 큐가 아니라 **학생별** FIFO 큐
// (__latencyQueues: studentId -> ms[])로 구현한다 — 45명 동시 매트릭스에서
// 서로 다른 학생의 호출이 이벤트 루프에서 뒤섞여도, 각 학생 자신의 호출
// 순서(그 학생의 시나리오 함수가 동기적으로 큐를 소비하는 순서)만으로
// 지연값이 정확히 배정되게 하기 위함이다(다른 학생과의 인터리빙에 영향받지
// 않음).
//
// 산출물: scripts/.tmp/(gitignore) — fakeSupabaseForWelcomeOnce.mjs /
// fakePinAuthWelcomeOnce.mjs / grantXp.welcomeOnce.bundle.mjs (이 파일
// 전용 이름, testTownV1Server.mjs/testTownShopServer.mjs가 쓰는 파일명과
// 충돌하지 않는다). 네트워크 0, production 요청 0, DB 무접촉.


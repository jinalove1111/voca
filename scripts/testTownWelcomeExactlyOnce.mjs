fs.writeFileSync(fakePath, `// AUTO-GENERATED by scripts/testTownWelcomeExactlyOnce.mjs
export const __db = { students: [], dollar_ledger: [] }
export const __fail = { rpc: null }
export const __calls = []
export const __latencyQueues = new Map() // studentId -> ms[] (FIFO, 학생별 독립)
export function __reset() {
  __db.students = []
  __db.dollar_ledger = []
  __fail.rpc = null
  __calls.length = 0
  __latencyQueues.clear()
}
export function __setLatencies(studentId, msList) {
  __latencyQueues.set(studentId, [...msList])
}

function balanceOf(studentId) {
  return __db.dollar_ledger.filter((e) => e.student_id === studentId).reduce((a, e) => a + e.dollars_delta, 0)
}
function tick() {
  // 최소한의 인위적 비동기 틈 — 이 틈이 없으면 동시 호출이 우연히
  // 직렬화돼(락 없이도 통과하는) 거짓 양성 테스트가 된다.
  return new Promise((resolve) => setTimeout(resolve, 0))
}
async function delayFor(studentId) {
  const q = __latencyQueues.get(studentId)
  const ms = (q && q.length) ? q.shift() : null
  if (typeof ms === 'number' && ms > 0) {
    await new Promise((resolve) => setTimeout(resolve, ms))
  } else {
    await tick()
  }
}

// grant_town_welcome_credit(p_student_id) — v3_50 SQL 본문 흉내.
// 주의: "중복 확인 + insert"는 이 함수 안에서 await 없이 동기적으로
// 이어진다(위 파일 헤더 설명) — 이게 UNIQUE 제약의 원자성을 재현하는
// 핵심이다. 지연은 그 앞에서만 발생시킨다(진짜 DB 왕복 지연 위치).
async function rpcWelcome(studentId) {
  await delayFor(studentId)
  const key = studentId + ':welcome:town-v1'
  const already = __db.dollar_ledger.some((e) => e.idempotency_key === key)
  if (already) return { granted: false, balance_after: balanceOf(studentId) }
  __db.dollar_ledger.push({ student_id: studentId, dollars_delta: 20, event_type: 'welcome:town-v1', idempotency_key: key })
  return { granted: true, balance_after: balanceOf(studentId) }
}

export function createClient() {
  return {
    from(table) {
      return {
        select() { return { eq() { return { maybeSingle: () => Promise.resolve({ data: null, error: null }) } } } },
        insert() { return Promise.resolve({ error: null }) },
      }
    },
    async rpc(name, args) {
      __calls.push({ rpc: name, args })
      if (__fail.rpc) return { data: null, error: __fail.rpc }
      if (name === 'grant_town_welcome_credit') {
        const row = await rpcWelcome(args.p_student_id)
        return { data: [row], error: null }
      }
      return { data: null, error: { code: 'XX000', message: 'unknown rpc ' + name } }
    },
  }
}
`, 'utf8')

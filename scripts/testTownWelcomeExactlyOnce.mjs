const { signSessionToken } = await import('../api/_pinAuth.js')

function tokenFor(sid, opts) { return signSessionToken(sid, opts) }

function res() {
  const r = { code: null, body: null }
  r.status = (c) => { r.code = c; return r }
  r.json = (b) => { r.body = b; return r }
  return r
}
function call(token, headers = {}) {
  const r = res()
  return handler({ method: 'POST', body: token === undefined ? {} : { action: 'claim_town_welcome', token }, headers }, r).then(() => r)
}
function callAction(body, headers = {}) {
  const r = res()
  return handler({ method: 'POST', body: body || {}, headers }, r).then(() => r)
}
function seedStudent(id, name) {
  if (!fake.__db.students.some((s) => s.id === id)) fake.__db.students.push({ id, name: name || id })
}
function reset() { fake.__reset() }
function rpcCallCount() { return fake.__calls.filter((c) => c.rpc === 'grant_town_welcome_credit').length }
function keyFor(sid) { return sid + ':welcome:town-v1' }
function ledgerRowsFor(sid) { return fake.__db.dollar_ledger.filter((e) => e.idempotency_key === keyFor(sid)) }
function sumFor(sid) { return ledgerRowsFor(sid).reduce((a, e) => a + e.dollars_delta, 0) }

function uuidFor(seed) {
  const hex = seed.toString(16).padStart(8, '0')
  return `${hex}-1111-4111-8111-11111111${hex.slice(0, 4)}`
}

function enableGate() { process.env.TOWN_V1_WELCOME_ENABLED = '1' }

// ── 시나리오 실행기 — 10가지 재사용 가능한 흐름 ─────────────────────────
// 각 함수는 { responses: Response[] }를 반환한다. 지연은 fake.__setLatencies
// 로 학생별 FIFO 큐에 미리 채워둔다(설계 근거는 파일 헤더 참고).
async function scenarioFirstVisit(sid) {
  const tk = tokenFor(sid)
  const r = await call(tk)
  return { responses: [r] }
}
async function scenarioRefresh(sid) {
  const tk = tokenFor(sid)
  const r1 = await call(tk)
  const r2 = await call(tk) // 같은 토큰으로 두 번째 핸들러 호출(새로고침)
  return { responses: [r1, r2] }
}
async function scenarioRelogin(sid) {
  const tk1 = tokenFor(sid)
  const r1 = await call(tk1)
  const tk2 = tokenFor(sid, { now: Date.now() + 1000 }) // 새 세션 토큰, 같은 studentId
  const r2 = await call(tk2)
  return { responses: [r1, r2] }
}
async function scenarioDoubleClick(sid) {
  const tk = tokenFor(sid)
  const [r1, r2] = await Promise.all([call(tk), call(tk)])
  return { responses: [r1, r2] }
}
async function scenarioTwoTabs(sid) {
  const tk1 = tokenFor(sid)
  const tk2 = tokenFor(sid, { now: Date.now() + 500 }) // 다른 토큰, 같은 학생
  const [r1, r2] = await Promise.all([call(tk1), call(tk2)])
  return { responses: [r1, r2] }
}
async function scenarioTwoDevicesSkew(sid) {
  const tk1 = tokenFor(sid)
  const tk2 = tokenFor(sid, { now: Date.now() + 500 })
  fake.__setLatencies(sid, [10, 200]) // 디바이스A 10ms(빠른 회선), 디바이스B 200ms(지연 회선)
  const [r1, r2] = await Promise.all([call(tk1), call(tk2)])
  return { responses: [r1, r2], fastIndex: 0, slowIndex: 1 }
}
async function scenarioSimultaneous10(sid) {
  const tk = tokenFor(sid)
  const responses = await Promise.all(Array.from({ length: 10 }, () => call(tk)))
  return { responses }
}
async function scenarioNetworkRetry(sid) {
  const tk = tokenFor(sid)
  const r1 = await call(tk) // 서버는 이미 커밋했지만 응답이 유실됐다고 가정
  const r2 = await call(tk) // 클라이언트 재전송
  return { responses: [r1, r2] }
}
async function scenarioSlowResponse(sid) {
  const tk1 = tokenFor(sid)
  const tk2 = tokenFor(sid, { now: Date.now() + 500 })
  fake.__setLatencies(sid, [800, 5]) // 첫 요청 800ms 지연 도중 두 번째 요청 도착(5ms, 빠르게 완료)
  const p1 = call(tk1)
  const p2 = call(tk2)
  const [r1, r2] = await Promise.all([p1, p2])
  return { responses: [r1, r2], slowIndex: 0, fastIndex: 1 }
}
async function scenarioTimeoutRetry(sid) {
  const tk1 = tokenFor(sid)
  fake.__setLatencies(sid, [300, 5]) // 첫 요청 300ms에 클라이언트가 포기(재시도 발사)하지만 서버는 계속 처리 -> 두 번째(재시도)는 5ms로 빠르게 완료
  const p1 = call(tk1) // 클라이언트가 응답을 기다리지 않고 포기한 요청(하지만 서버는 취소되지 않고 계속 진행)
  const tk2 = tokenFor(sid, { now: Date.now() + 10 })
  const p2 = call(tk2) // 재시도
  const [r1, r2] = await Promise.all([p1, p2])
  return { responses: [r1, r2] }
}

const SCENARIOS = [
  ['first_visit', scenarioFirstVisit],
  ['refresh', scenarioRefresh],
  ['relogin', scenarioRelogin],
  ['double_click', scenarioDoubleClick],
  ['two_tabs', scenarioTwoTabs],
  ['two_devices_skew', scenarioTwoDevicesSkew],
  ['simultaneous_10', scenarioSimultaneous10],
  ['network_retry', scenarioNetworkRetry],
  ['slow_response', scenarioSlowResponse],
  ['timeout_retry', scenarioTimeoutRetry],
]

function assertExactlyOnce(label, sid, result) {
  const rows = ledgerRowsFor(sid)
  check(`${label}: dollar_ledger welcome 행 정확히 1개`, rows.length === 1)
  check(`${label}: dollars_delta 합계 정확히 20`, sumFor(sid) === 20)
  const grantedTrueCount = result.responses.filter((r) => r.body && r.body.granted === true).length
  check(`${label}: granted:true 응답 정확히 1회`, grantedTrueCount === 1)
  check(`${label}: 모든 응답 balanceAfter === 20`, result.responses.every((r) => r.body && r.body.balanceAfter === 20))
  check(`${label}: 모든 응답 ok === true`, result.responses.every((r) => r.body && r.body.ok === true))
}


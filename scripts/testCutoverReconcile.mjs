// reconcile_legacy_baseline(p_student_id, p_snapshot_total) 계약 그대로
// (CONTEXT 주석 원문): 학생 존재 -> 스냅샷 범위 -> 학생별 락 -> earned =
// reward_totals(student) -> v2 행 존재? already_reconciled -> snapshot >
// uploaded+200? review -> delta = snapshot-earned; delta<=0? 0-delta 행
// 삽입, nothing_to_reconcile -> delta > historySince+100 또는 > 1500?
// review(행 없음) -> v2 행 삽입(unique_violation은 already_reconciled로) ->
// reconciled, earned_after = earned+delta.
function rpcReconcileLegacyBaseline(studentId, snapshotTotal) {
  return withStudentLock(studentId, async () => {
    const student = __db.students.find((s) => s.id === studentId)
    if (!student) return { ok: false, reason: 'student_not_found', baseline_stars: 0, earned_after: 0 }
    if (!Number.isInteger(snapshotTotal) || snapshotTotal < 0 || snapshotTotal > 100000) {
      return { ok: false, reason: 'invalid_snapshot', baseline_stars: 0, earned_after: rewardTotalsFor(studentId) }
    }
    const existing = v2RowFor(studentId)
    if (existing) {
      return { ok: true, reason: 'already_reconciled', baseline_stars: existing.stars_delta, earned_after: rewardTotalsFor(studentId) }
    }
    const earned = rewardTotalsFor(studentId)
    const progress = __db.student_progress[studentId] || { total_stars: 0, historySince: 1000000 }
    const uploaded = Number(progress.total_stars) || 0
    if (snapshotTotal > uploaded + 200) {
      return { ok: false, reason: 'review', baseline_stars: 0, earned_after: earned }
    }
    const delta = snapshotTotal - earned
    if (delta <= 0) {
      insertV2Row(studentId, 0)
      return { ok: true, reason: 'nothing_to_reconcile', baseline_stars: 0, earned_after: rewardTotalsFor(studentId) }
    }
    const historySinceRaw = Number(progress.historySince)
    const historySince = Number.isFinite(historySinceRaw) ? historySinceRaw : 1000000
    if (delta > historySince + 100 || delta > 1500) {
      return { ok: false, reason: 'review', baseline_stars: 0, earned_after: earned }
    }
    if (v2RowFor(studentId)) {
      // 방어적 재확인(실제 DB의 unique_violation에 해당) — 이 인메모리
      // 락으로는 실질적으로 도달하지 않지만 계약을 그대로 흉내낸다.
      const row = v2RowFor(studentId)
      return { ok: true, reason: 'already_reconciled', baseline_stars: row.stars_delta, earned_after: rewardTotalsFor(studentId) }
    }
    insertV2Row(studentId, delta)
    return { ok: true, reason: 'reconciled', baseline_stars: delta, earned_after: rewardTotalsFor(studentId) }
  })
}


// ── "디바이스" — 학생 브라우저의 로컬 별 총합 + 대기 중인 지급 큐를 흉내
// 낸다. grant()는 로컬 총합을 즉시 올리고 큐에 넣는다(fire-and-forget과
// 동일하게 실제 POST는 나중에 flush()가 보낸다). reconcile()은 반드시
// "먼저 flush, 그 다음 snapshot 전송"(레이스를 닫는 설계) 순서를 지킨다.
class Device {
  constructor(studentId, token, legacyTotal) {
    this.studentId = studentId
    this.token = token
    this.localTotal = legacyTotal
    this.pending = []
    this.hold = false
    // 생성 시점에 "이미 이 값으로 한 번 업로드된 상태"로 시작한다 — 실제
    // 앱에서 legacy 총합은 이미 여러 번 디바운스 업로드를 거쳐 서버에
    // 반영돼 있는 값이기 때문(§1이 명시적으로 upload()를 부르지 않아도
    // review 가드에 걸리지 않아야 하는 이유).
    fake.__db.student_progress[studentId] = { total_stars: legacyTotal, historySince: 1000000 }
  }
  grant(amount, evt) {
    const item = { amount, ...evt }
    this.localTotal += amount
    this.pending.push(item)
    return item
  }
  async flush() {
    const items = this.pending.slice()
    for (const item of items) {
      const r = await call({
        ledger: 'reward', studentId: this.studentId,
        rewardType: item.rewardType, sourceType: item.sourceType, sourceId: item.sourceId,
        token: this.token,
      })
      item.lastResult = r.body
      if (r.body && r.body.ok) {
        const idx = this.pending.indexOf(item)
        if (idx >= 0) this.pending.splice(idx, 1)
      }
    }
  }
  upload() {
    const row = fake.__db.student_progress[this.studentId] || { total_stars: 0, historySince: 1000000 }
    row.total_stars = this.localTotal
    fake.__db.student_progress[this.studentId] = row
  }
  // opts.midpoint(device) — snapshot 값을 이미 확정한 "직후"(RPC 응답을
  // 기다리는 동안)에 실행된다. §4("hold 중 이벤트")가 이 훅으로 "스냅샷에는
  // 안 잡히지만 이후 flush로는 반영되는" 이벤트를 흉내낸다.
  async reconcile(opts = {}) {
    this.hold = true
    await this.flush()
    let result = null
    if (this.pending.length === 0) {
      const snapshot = this.localTotal
      if (typeof opts.midpoint === 'function') opts.midpoint(this)
      const r = await call({ action: 'reconcile_legacy_baseline', snapshotTotal: snapshot, token: this.token })
      result = r.body
    }
    this.hold = false
    await this.flush()
    return result
  }
}


function withStudentLock(studentId, fn) {
  const prev = __locks.get(studentId) || Promise.resolve()
  let release
  const gate = new Promise((resolve) => { release = resolve })
  __locks.set(studentId, prev.then(() => gate))
  return prev.then(async () => {
    try {
      return await fn()
    } finally {
      release()
    }
  })
}


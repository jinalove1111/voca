// Derives src/assets/town/kit/kitSizes.js (target -> [w, h], skipped omitted) from manifest.json.
// Runtime code only needs 1x sizes; importing the full manifest shipped ~17 KB of unused provenance fields.
// Re-run after buildTownKit.py regenerates manifest.json (testTownKitAssets pins the two in sync).
import fs from 'node:fs'
import path from 'node:path'

const KIT = path.resolve(import.meta.dirname, '../../src/assets/town/kit')
export const kitSizesSource = () => {
  const { targets } = JSON.parse(fs.readFileSync(path.join(KIT, 'manifest.json'), 'utf8'))
  const sizes = {}
  for (const [t, m] of Object.entries(targets)) if (!m.skipped) sizes[t] = [m.w, m.h]
  return `// GENERATED by scripts/town/buildKitSizes.mjs from manifest.json — do not hand-edit.\nexport default ${JSON.stringify(sizes)}\n`
}
if (process.argv[1] === import.meta.filename) fs.writeFileSync(path.join(KIT, 'kitSizes.js'), kitSizesSource())

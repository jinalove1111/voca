// scripts/testRewardCapRace.mjs
//
// Reward System V1 서버측 일일 상한(L3, api/grant-xp.js ~424-457) — 동시
// 요청 TOCTOU(Time-Of-Check-To-Time-Of-Use) 레이스 관측용 테스트. 결정
// 지원용(non-gating, extra:true) — "이 레이스가 있으면 안 된다"를 주장하지
// 않고, "지금 실제로 이런 동작이 관측된다"를 정직하게 고정한다(운영자가
// DB 레벨 가드 도입 여부를 판단할 때 근거로 쓰기 위함).
//
// ── 배경(읽기 전용 분석) ────────────────────────────────────────────────
// api/grant-xp.js의 일일 상한 검사는 "SELECT count → count < cap이면
// INSERT"(check-then-insert)다. DB 유일성 제약은 idempotency_key(요청당
// 1건, 같은 이벤트의 재시도만 막는다) 하나뿐이고, (student_id, reward_type,
// day) 조합에는 유일성 제약이 없다 — 즉 서로 다른 sourceId(=서로 다른
// idempotency_key)를 가진 동시 요청 N개가 count = cap-1인 순간에 도착하면
// 전부 "아직 상한 미만"으로 읽어(각자 정확한 값을 읽지만 서로의 쓰기를
// 못 봄) 전부 INSERT를 시도하고, 서로 다른 키라 23505 충돌도 없이 전부
// 성공할 수 있다 — 최종 건수가 cap을 최대 N-1건 초과한다.
//
// scripts/testRewardServerHardeningBehavior.mjs §7(~248-262)은 상한
// 도달을 "순차" 호출로만 검증하고, §3(~190-197)의 Promise.all은 "같은
// 이벤트"(같은 sourceId → 같은 idempotency_key) 동시 20회만 다뤄
// idempotency만 확인한다 — 서로 다른 sourceId의 진짜 카운트 레이스는 그
// 파일도, 다른 어떤 등록된 테스트도 다루지 않는다. 이 파일이 그 공백을
// 메운다.
//
// ── 하네스 설계 — 정직한 TOCTOU 모델링 ───────────────────────────────────
// scripts/testRewardServerHardeningBehavior.mjs가 만드는
// scripts/.tmp/fakeSupabaseForRewardApi.mjs는 그 파일이 "실행 시" 스스로
// 생성하는 산출물이라 이 파일이 import해서 재사용할 안정적인 모듈이
// 아니다(그 파일을 수정하지 않는다는 원칙과 별개로, 애초에 참조 가능한
// 공유 소스가 없다) — 그래서 이 파일은 같은 스타일(esbuild + 인메모리 가짜
// @supabase/supabase-js)을 따르되 완전히 독립된 가짜 DB를 자체 생성한다.
//
// 이 가짜 DB의 일일 상한 COUNT 쿼리는 "즉시 응답"이 아니라 "배리어(barrier)"
// 방식으로 동작한다 — 실제 동시 HTTP 요청 N개가 거의 같은 시각에 각자
// COUNT를 실행하면, 그 N개의 SELECT 각각은 호출 시점의 정확한 값을
// 돌려주지만(진짜 DB의 SELECT는 항상 정직하다), 그 응답이 클라이언트(=이
// 핸들러)에 돌아오는 시각은 네트워크/DB 왕복 지연 때문에 서로 겹친다 — 즉
// N개 요청 전부가 "아직 아무도 INSERT하지 않은" 시점의 카운트를 손에 쥔
// 채로 각자 INSERT를 결정한다. 이를 정직하게 재현하기 위해, cap-count
// SELECT는 호출 시점에 값을 스냅샷(정확한 값)해 두고, 그 Promise의 resolve는
// 같은 배리어에 걸린 SELECT가 N개 모일 때까지 보류한다 — "테스트가 결과를
// 조작"하는 게 아니라 "N개의 동시 요청이 실제로 서로의 쓰기를 보지 못하는
// 창(window)"을 결정론적으로 만드는 것이다. 순차(비동시) 시나리오는 배리어
// 크기를 1로 둬 매 SELECT가 즉시 응답하므로(레이스 없음) 정상적인
// check-then-insert가 그대로 재현된다 — 즉 시퀀셜 케이스는 기존
// testRewardServerHardeningBehavior.mjs §7과 동일한 "상한이 정확히
// 강제된다"를 회귀 대조군으로 다시 확인한다.
//
// 등록: npm run verify:reward-cap-race (extra:true, non-gating)
// production 요청 0, 실제 DB 접촉 0. api/grant-xp.js/rewardEngine.js는
// 한 글자도 수정하지 않고 esbuild로 그대로 번들해 구동한다.


const handler = (await import(pathToFileURL(outfile).href)).default
const { REWARD_DAILY_CAP } = await import('../src/utils/rewardEngine.js')

process.env.SESSION_SECRET = 'reward-cap-race-test-secret'
const { signSessionToken } = await import('../api/_pinAuth.js')

const STUDENT = 'aaaaaaaa-1111-4222-8333-444444444444'
const today = new Date().toDateString()
const tokenFor = (sid) => signSessionToken(sid)

function res() {
  const r = { code: null, body: null }
  r.status = (c) => { r.code = c; return r }
  r.json = (b) => { r.body = b; return r }
  return r
}
function post(body) {
  const withAuth = (body.token === undefined) ? { ...body, token: tokenFor(body.studentId) } : body
  const r = res()
  return handler({ method: 'POST', body: withAuth, headers: {} }, r).then(() => r)
}
function seedAtCapMinusOne(rewardType, n) {
  fake.__reset()
  fake.__db.students.push({ id: STUDENT })
  for (let i = 0; i < n; i++) {
    fake.__db.reward_ledger.push({
      student_id: STUDENT, reward_type: rewardType, idempotency_key: `seed-${rewardType}-${i}`,
      stars_delta: 1, created_at: new Date().toISOString(),
    })
  }
}
const rewardType = 'pronunciation' // cap 120 — REWARD_DAILY_CAP['pronunciation'], rewardEngine.js:556
const cap = REWARD_DAILY_CAP[rewardType]
const reqBody = (i) => ({
  ledger: 'reward', studentId: STUDENT, rewardType,
  sourceType: 'pronunciation', sourceId: `raceTok${i}:${today}`,
})

console.log(`\n0. 픽스처 확인 — rewardType='${rewardType}' 상한(cap) = ${cap}`)
check('cap이 최소 5 이상(N=5 동시 요청 시나리오를 담기 위한 전제)', cap >= 5)

console.log('\n1. 회귀 대조군(순차) — N개 순차 요청이면 상한이 정확히 강제된다')
{
  fake.__setCapBarrier(1) // 배리어 없음 = 매 SELECT 즉시 응답(레이스 없음)
  seedAtCapMinusOne(rewardType, cap - 1)
  const N = 3
  const results = []
  for (let i = 0; i < N; i++) results.push(await post(reqBody(`seq${i}`)))
  const oks = results.filter((r) => r.body?.ok === true).length
  const capped = results.filter((r) => r.body?.reason === 'daily_cap_reached').length
  check(`순차 ${N}회 중 정확히 1건 성공(count=cap-1에서 시작)`, oks === 1)
  check(`나머지 ${N - 1}건은 daily_cap_reached로 거부`, capped === N - 1)
  check(`원장 최종 건수 = cap(${cap}) — 초과 없음`, fake.__db.reward_ledger.length === cap)
}

console.log('\n2. ★ 동시 요청(Promise.all) — 서로 다른 sourceId N개가 count=cap-1에서 경합')
{
  const N = 5
  fake.__setCapBarrier(N) // N개의 cap-count SELECT가 다 모여야 응답(정직한 TOCTOU 창)
  seedAtCapMinusOne(rewardType, cap - 1)
  const results = await Promise.all(Array.from({ length: N }, (_, i) => post(reqBody(`race${i}`))))
  const successCount = results.filter((r) => r.body?.ok === true).length
  const cappedCount = results.filter((r) => r.body?.reason === 'daily_cap_reached').length
  console.log(`  관측: 동시 ${N}건 중 성공 ${successCount}건, 거부 ${cappedCount}건, 원장 최종 ${fake.__db.reward_ledger.length}건(시작 ${cap - 1}건 + 성공분)`)
  console.log(`  관측된 초과분(overshoot) = 성공 ${successCount}건 - 상한상 기대 1건 = ${successCount - 1}`)
  check('성공 건수는 1 이상 N 이하(핸들러가 크래시하거나 전부 거부되지 않음)', successCount >= 1 && successCount <= N)
  check('원장 최종 건수 = 시작(cap-1) + 성공 건수(정합성)', fake.__db.reward_ledger.length === (cap - 1) + successCount)
  check(
    'KNOWN GAP (결정 대기): 동시 요청이 상한을 초과할 수 있다 — DB 레벨 (student,type,day) 가드 부재. ' +
    '이 단언은 "지금 이 동작이 실제로 재현된다"를 기록하는 것이지 바람직하다는 뜻이 아니다 — DB 가드가 ' +
    '도입되면 successCount는 항상 1이 되어 이 단언은 뒤집힌다(그때 이 테스트를 반드시 함께 갱신할 것).',
    successCount > 1,
  )
}

console.log('\n3. 대조군 — 같은 이벤트(같은 sourceId) 동시 N회는 여전히 정확히 1건만 (idempotency 무회귀)')
{
  fake.__setCapBarrier(1) // idempotency 방어는 배리어와 무관 — insert 자체가 동기적으로 직렬화된다
  seedAtCapMinusOne(rewardType, 0)
  const N = 8
  const sameBody = reqBody('same-event')
  const results = await Promise.all(Array.from({ length: N }, () => post(sameBody)))
  check(`동시 ${N}회(같은 sourceId) -> 원장 정확히 1건`, fake.__db.reward_ledger.length === 1)
  check('성공 응답 중 duplicate:false는 정확히 1건, 나머지는 duplicate:true 또는 성공(23505 흡수)',
    results.every((r) => r.body?.ok === true))
}

console.log(`\n총 단언 ${asserted}개 중 실패 ${failures}개`)
